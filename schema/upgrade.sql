-- Kloud Kart: schema upgrade. Turns the as-is schema (M03_Resources/schema.sql, left untouched as the
-- baseline) into one that keeps the cleaned data clean and takes new data safely at flash-sale volume.
-- Order: schema.sql + load.sql (fresh load) -> relationDATA/relationship.sql -> cleaning/clean_all.sql -> this.
-- Re-runnable. Decisions and rejected alternatives: ADR/0005.
--   docker exec kloudkart-db psql -U kloudkart -d kloudkart -f /schema/upgrade.sql

\set ON_ERROR_STOP on
BEGIN;

-- 1. ID SIZE. Orders, order lines and stock movements are the tables that grow with every sale.
--    bigint removes the 2.1 billion ceiling of integer and matches place_order's bigint contract.
--    Parent keys first, then the columns that point at them.
ALTER TABLE orders        ALTER COLUMN order_id      TYPE bigint;
ALTER TABLE order_items   ALTER COLUMN order_item_id TYPE bigint,
                          ALTER COLUMN order_id      TYPE bigint;
ALTER TABLE inventory_log ALTER COLUMN log_id        TYPE bigint;

-- 2. AUTOMATIC IDS. No table could create its own key, so every writer had to invent one (max + 1),
--    which collides when 400 buyers arrive at once. BY DEFAULT, not ALWAYS: explicit ids still work,
--    which race_test.py needs for its fixture products. Each sequence starts after the highest id.
DO $$
DECLARE r record;
BEGIN
    FOR r IN SELECT * FROM (VALUES ('categories', 'category_id'), ('customers', 'customer_id'),
                                   ('products', 'product_id'),    ('orders', 'order_id'),
                                   ('order_items', 'order_item_id'), ('inventory_log', 'log_id')) t(tbl, col)
    LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_attribute
                       WHERE attrelid = r.tbl::regclass AND attname = r.col AND attidentity <> '') THEN
            EXECUTE format('ALTER TABLE %I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY', r.tbl, r.col);
        END IF;
        EXECUTE format('SELECT setval(pg_get_serial_sequence(%L, %L), (SELECT coalesce(max(%I), 0) + 1 FROM %I), false)',
                       r.tbl, r.col, r.col, r.tbl);
    END LOOP;
END $$;

-- 3. REQUIRED VALUES. Every column with no NULLs after cleaning that a row cannot make sense without.
--    Left nullable on purpose: categories.parent_id (top-level), products.category_id (race_test fixtures),
--    order_items.unit_price (148 lines under review), customers.phone/city, inventory_log.note.
ALTER TABLE categories    ALTER COLUMN category_name  SET NOT NULL;
ALTER TABLE customers     ALTER COLUMN full_name      SET NOT NULL,
                          ALTER COLUMN email          SET NOT NULL,
                          ALTER COLUMN registered_at  SET NOT NULL;
ALTER TABLE products      ALTER COLUMN product_name   SET NOT NULL,
                          ALTER COLUMN price          SET NOT NULL,
                          ALTER COLUMN stock_quantity SET NOT NULL,
                          ALTER COLUMN created_at     SET NOT NULL;
ALTER TABLE orders        ALTER COLUMN customer_id    SET NOT NULL,
                          ALTER COLUMN order_date     SET NOT NULL,
                          ALTER COLUMN status         SET NOT NULL,
                          ALTER COLUMN total_amount   SET NOT NULL;
ALTER TABLE order_items   ALTER COLUMN order_id       SET NOT NULL,
                          ALTER COLUMN product_id     SET NOT NULL,
                          ALTER COLUMN quantity       SET NOT NULL;
ALTER TABLE inventory_log ALTER COLUMN product_id     SET NOT NULL,
                          ALTER COLUMN change_qty     SET NOT NULL,
                          ALTER COLUMN reason         SET NOT NULL,
                          ALTER COLUMN created_at     SET NOT NULL;

-- 4. DEFAULTS, so a writer only supplies what it actually knows.
ALTER TABLE customers     ALTER COLUMN registered_at  SET DEFAULT now();
ALTER TABLE products      ALTER COLUMN created_at     SET DEFAULT now(),
                          ALTER COLUMN stock_quantity SET DEFAULT 0;
ALTER TABLE orders        ALTER COLUMN order_date     SET DEFAULT now(),
                          ALTER COLUMN status         SET DEFAULT 'pending';
ALTER TABLE inventory_log ALTER COLUMN created_at     SET DEFAULT now();

-- 5. VALUE RULES. Each one is a problem found in the diagnosis that can no longer be written.
ALTER TABLE categories DROP CONSTRAINT IF EXISTS chk_categories_not_own_parent,
    ADD CONSTRAINT chk_categories_not_own_parent CHECK (parent_id <> category_id);

ALTER TABLE customers DROP CONSTRAINT IF EXISTS chk_customers_email,
    ADD CONSTRAINT chk_customers_email
        CHECK (email = lower(btrim(email)) AND email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$');

ALTER TABLE products DROP CONSTRAINT IF EXISTS chk_products_price,
    ADD CONSTRAINT chk_products_price CHECK (price > 0);

ALTER TABLE orders DROP CONSTRAINT IF EXISTS chk_orders_total,
    ADD CONSTRAINT chk_orders_total CHECK (total_amount >= 0);

ALTER TABLE order_items DROP CONSTRAINT IF EXISTS chk_order_items_unit_price,
    ADD CONSTRAINT chk_order_items_unit_price CHECK (unit_price >= 0);

ALTER TABLE inventory_log DROP CONSTRAINT IF EXISTS chk_inventory_log_reason,
    ADD CONSTRAINT chk_inventory_log_reason
        CHECK (reason IN ('sale', 'restock', 'return', 'correction', 'damage', 'stock_take'));

-- Direction must match the reason (negative = stock out); a correction must actually change something.
ALTER TABLE inventory_log DROP CONSTRAINT IF EXISTS chk_inventory_log_direction,
    ADD CONSTRAINT chk_inventory_log_direction CHECK (
        (reason IN ('sale', 'damage')     AND change_qty < 0) OR
        (reason IN ('restock', 'return')  AND change_qty > 0) OR
        (reason = 'correction'            AND change_qty <> 0) OR
        (reason = 'stock_take'            AND change_qty = 0));

-- 6. AUDIT TRAIL. Every new sale movement names its order, and every movement records who wrote it.
--    The cleaning could not tell a double entry from a real repeat purchase because this link was missing.
--    Checked at COMMIT (DEFERRABLE INITIALLY DEFERRED): an order that still has movements can never be
--    deleted, yet a transaction that removes both (race_test.py's cleanup deletes the order first, then its
--    movements, then commits) still works. SET NULL was rejected: it would blank the link and break the
--    "every sale names its order" rule below.
ALTER TABLE inventory_log
    ADD COLUMN IF NOT EXISTS order_id   bigint,
    ADD COLUMN IF NOT EXISTS created_by text NOT NULL DEFAULT current_user;

ALTER TABLE inventory_log DROP CONSTRAINT IF EXISTS fk_inventory_log_order,
    ADD CONSTRAINT fk_inventory_log_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id) DEFERRABLE INITIALLY DEFERRED;

-- NOT VALID: the 262k historical sale movements have no order and never will; every new one must.
ALTER TABLE inventory_log DROP CONSTRAINT IF EXISTS chk_inventory_log_sale_has_order,
    ADD CONSTRAINT chk_inventory_log_sale_has_order
        CHECK (reason <> 'sale' OR order_id IS NOT NULL) NOT VALID;

-- 7. DOCUMENTATION in the database itself, for Nana's team after handover.
COMMENT ON TABLE  inventory_log IS 'Every stock movement. Negative change_qty = stock out. New sales carry order_id.';
COMMENT ON COLUMN inventory_log.order_id   IS 'Order that caused a sale movement. NULL for history before the 2026-11 upgrade.';
COMMENT ON COLUMN inventory_log.created_by IS 'Database user that wrote the movement.';
COMMENT ON COLUMN orders.total_amount      IS 'Figure of record for what the customer was charged (written at checkout).';
COMMENT ON COLUMN orders.order_date        IS 'Local Accra time (GMT, no daylight saving).';
COMMENT ON COLUMN products.stock_quantity  IS 'Units on hand. Changed only through place_order or a logged movement. Never below 0.';
COMMENT ON COLUMN order_items.unit_price   IS 'Price at the time of sale; may differ from products.price.';

COMMIT;

-- What is now enforced, per table.
SELECT conrelid::regclass AS table_name,
       count(*) FILTER (WHERE contype = 'f') AS foreign_keys,
       count(*) FILTER (WHERE contype = 'c') AS checks,
       count(*) FILTER (WHERE contype = 'c' AND NOT convalidated) AS checks_new_rows_only
FROM pg_constraint
WHERE connamespace = 'public'::regnamespace AND contype IN ('f', 'c')
GROUP BY 1 ORDER BY 1::text;
